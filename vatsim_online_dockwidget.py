import os
from pathlib import Path

from PyQt5.QtGui import QColor
from qgis.PyQt import QtWidgets, uic
from qgis.PyQt.QtCore import pyqtSignal
from qgis._core import QgsMessageLog, Qgis, QgsProject
from dotenv import load_dotenv, dotenv_values

from.history_layer import HistoryLayer
from .live_aircraft_layer import VatsimAircraftLayer
from .vatsim_data import VatsimData
from .update_data_thread import VatsimUpdateThread

FORM_CLASS, _ = uic.loadUiType(os.path.join(
    str(os.path.dirname(__file__)), 'vatsim_online_dockwidget_base.ui'))

plugin_dir = Path(__file__).resolve().parent
env_path = plugin_dir / '.env'
load_dotenv(dotenv_path=env_path)

class VatsimOnlineDockWidget(QtWidgets.QDockWidget, FORM_CLASS):

    closingPlugin = pyqtSignal()

    def __init__(self, parent=None):
        """Constructor."""
        super(VatsimOnlineDockWidget, self).__init__(parent)
        # Set up the user interface from Designer.
        # After setupUI you can access any designer object by doing
        # self.<objectname>, and you can use autoconnect slots - see
        # http://doc.qt.io/qt-5/designer-using-a-ui-file.html
        # #widgets-and-dialogs-with-auto-connect
        self.setupUi(self)
        self.vatsim_data_url = os.getenv("VATSIM_DATA_URL")
        self.afv_transceivers_url = os.getenv("AFV_TRANSCEIVERS_URL")
        self.vatsim_data_refresh_rate = os.getenv("REFRESH_TIME_SECS")  # Seconds
        self.vatsim_data = VatsimData(self.vatsim_data_url)
        self.fetching_data = False
        self.vatsim_layer = None
        self.history_layer = None
        self.update_thread = None
        self.is_updating = False
        self.debug = False
        self.hidden_vatsim_id = self.spnVatsimId.value()

        project_path = QgsProject.instance().homePath()
        if project_path:
            self.mHistoryFile.setDefaultRoot(project_path)
            layer_uri = HistoryLayer.find_existing_layer()
            if layer_uri is not None:
                layer_source = layer_uri.source().partition('|')[0]
                self.mHistoryFile.setFilePath(layer_source)


    def closeEvent(self, event, **kwargs):
        if self.is_updating:
            self._stop_updating()
        self.closingPlugin.emit()
        event.accept()


    def debug_update(self):
        self.debug = False

    def history_be_recorded(self) -> bool:
        return self.chkHistory.isChecked()

    def on_btn_get_data_released(self):
        """Toggle between start/stop updating."""
        if self.is_updating:
            self._stop_updating()
        else:
            self._start_updating()


    def _start_updating(self):
        """Start the auto-update thread."""
        refresh_rate = self.spnRefreshRate.value()
        self.hidden_vatsim_id = self.spnVatsimId.value()

        # Setup UI
        self.is_updating = True
        self.update_ui_state()

        # Create and configure thread
        self.update_thread = VatsimUpdateThread(
            self.vatsim_data,
            self.vatsim_layer,
            refresh_rate,
            self.history_layer,
            self.hidden_vatsim_id,
            self.debug
        )

        # Connect signals
        self.update_thread.update_complete.connect(self._handle_update_result)
        self.update_thread.log_message.connect(self._log_message)

        # Start thread
        self.update_thread.start()
        self._log_message(f"Started updates every {refresh_rate}s", Qgis.MessageLevel.Info)


    def _stop_updating(self):
        """Stop the auto-update thread."""
        if self.update_thread:
            self.update_thread.stop()
            self.update_thread = None

        # Reset UI
        self.is_updating = False
        self.update_ui_state()
        self._log_message("Updates stopped", Qgis.MessageLevel.Info)


    def _handle_update_result(self, success):
        """Handle completion of an update cycle."""
        # Can add post-update logic here if needed
        pass


    @staticmethod
    def _log_message(message, level: Qgis.MessageLevel=Qgis.MessageLevel.Info):
        """Thread-safe logging."""
        QgsMessageLog.logMessage(message, level=level)


    def update_ui_state(self):
        self.spnRefreshRate.setEnabled(not self.is_updating)
        self.spnVatsimId.setEnabled(not self.is_updating)
        self.mColorButton.setEnabled(not self.is_updating)
        self.chkHistory.setEnabled(not self.is_updating)
        self.mHistoryFile.setEnabled(not self.is_updating)

        button_text = "Stop Updating" if self.is_updating else "Get Data"
        self.btnGetData.setText(button_text)
        button_style = "background-color: #4CAF50; color: white;" if self.is_updating else ""
        self.btnGetData.setStyleSheet(button_style)

        if not self.is_updating:
            self.vatsim_layer.rename_layer("VATSIM Data Snapshot")
            self.history_layer.create_spatial_index() if self.history_be_recorded() else None

        self.vatsim_layer = VatsimAircraftLayer(aircraft_colour=self.mColorButton.color(), layer_name="VATSIM Data") if self.is_updating else None

        if self.history_be_recorded() and self.is_updating:
            self.history_layer = HistoryLayer()
        else:
            self.history_layer = None
